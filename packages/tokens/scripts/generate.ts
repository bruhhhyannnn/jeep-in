/**
 * Writes the outputs of src/index.ts:
 *   - tailwind-preset.cjs, the Tailwind v3 preset the commuter apps use
 *   - the CSS variable block in each commuter app's app/global.css
 *
 * NativeWind can't reliably import CSS from a package, so the variables are written
 * into each app's own stylesheet between the markers below.
 *
 *   npm run tokens            write the files
 *   npm run tokens -- --check fail if any file is out of date (runs with lint)
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";
import {
  fonts,
  palette,
  radii,
  ramps,
  shadows,
  themeColorKeys,
} from "../src/index";

const pkg = fileURLToPath(new URL("..", import.meta.url));
const repo = path.resolve(pkg, "../..");

const PRESET = path.join(pkg, "tailwind-preset.cjs");
const STYLESHEETS = [
  "apps/mobile-commuter/app/global.css",
  "apps/web-commuter/app/global.css",
];

const START =
  "/* @generated by @jeep-in/tokens: edit packages/tokens/src/index.ts, then run `npm run tokens`. */";
const END = "/* @end-generated */";

const check = process.argv.includes("--check");

const kebab = (key: string) =>
  key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

/** "#1670e0" → "22 112 224", so Tailwind can apply opacity (`bg-action/40`). */
function channels(hex: string) {
  const n = Number.parseInt(hex.slice(1), 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
}

function cssVariables() {
  const block = (scheme: keyof typeof palette) =>
    [
      ...themeColorKeys.map(
        (key) => `--${kebab(key)}: ${channels(palette[scheme][key])};`,
      ),
      ...Object.entries(shadows[scheme]).map(
        ([size, s]) => `--shadow-${size}: ${s.boxShadow};`,
      ),
    ].join("\n");
  return `${START}\n:root {\n${block("light")}\n}\n\n.dark:root {\n${block("dark")}\n}\n${END}`;
}

function preset() {
  const sans = ["system-ui", "sans-serif"];
  const mono = ["ui-monospace", "monospace"];
  // Apps set darkMode themselves: NativeWind's preset sets it too, and an app's own
  // config is the only place that outranks every preset.
  const config = {
    theme: {
      extend: {
        // Semantic colours resolve through the CSS variables, so they switch with
        // the Appearance setting.
        colors: {
          ...Object.fromEntries(
            themeColorKeys.map((key) => [
              kebab(key),
              `rgb(var(--${kebab(key)}) / <alpha-value>)`,
            ]),
          ),
          ...ramps,
        },
        borderRadius: Object.fromEntries(
          Object.entries(radii).map(([name, px]) => [name, `${px}px`]),
        ),
        boxShadow: Object.fromEntries(
          Object.keys(shadows.light).map((size) => [
            size,
            `var(--shadow-${size})`,
          ]),
        ),
        // One family per weight. Named so they don't clash with font-medium /
        // font-bold, which would fake-bold a bold face.
        fontFamily: {
          puffin: [fonts.regular, ...sans],
          "puffin-medium": [fonts.medium, ...sans],
          "puffin-semibold": [fonts.semibold, ...sans],
          "puffin-bold": [fonts.bold, ...sans],
          moment: [fonts.moment, ...sans],
          mono: [fonts.mono, ...mono],
          "mono-bold": [fonts.monoBold, ...mono],
        },
      },
    },
  };
  return [
    "// @generated by @jeep-in/tokens: edit src/index.ts, then run `npm run tokens`.",
    "/** @type {import('tailwindcss').Config} */",
    `module.exports = ${JSON.stringify(config, null, 2)};`,
  ].join("\n");
}

async function format(file: string, source: string) {
  const options = await prettier.resolveConfig(file);
  return prettier.format(source, { ...options, filepath: file });
}

async function readOrEmpty(file: string) {
  return readFile(file, "utf8").catch(() => "");
}

const stale: string[] = [];

async function emit(file: string, next: string) {
  const current = await readOrEmpty(file);
  if (current === next) return;
  if (check) stale.push(path.relative(repo, file));
  else await writeFile(file, next);
}

await emit(PRESET, await format(PRESET, preset()));

for (const relative of STYLESHEETS) {
  const file = path.join(repo, relative);
  const current = await readFile(file, "utf8");
  const start = current.indexOf(START);
  const end = current.indexOf(END);
  if (start === -1 || end === -1) {
    throw new Error(
      `${relative} is missing the generated-token markers:\n${START}\n${END}`,
    );
  }
  const next =
    current.slice(0, start) + cssVariables() + current.slice(end + END.length);
  await emit(file, await format(file, next));
}

if (stale.length) {
  console.error(
    `Out of date, run \`npm run tokens\`:\n  ${stale.join("\n  ")}`,
  );
  process.exit(1);
}
console.log(check ? "Tokens are up to date." : "Tokens written.");
